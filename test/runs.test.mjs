test('run review finds command-only and log-only runs, includes undo ancestry, paginates and survives restart', t => {
  const directory = mkdtempSync(path.join(tmpdir(), 'pageyard-run-review-'));
  let workspace = new Workspace(directory), sequence = 0;
  t.after(() => { workspace.close(); rmSync(directory, { recursive: true, force: true }); });
  const apply = (operations, runId) => workspace.execute({ id: `c${++sequence}`, actor: runId ? 'agent' : 'user', expectedRevision: workspace.revision, operations, ...(runId ? { runId } : {}) });
  apply([{ type: 'page.create', id: 'doc', title: '원문' }, { type: 'block.create', id: 'body', parentId: 'doc', richText: [{ text: '보존할 본문' }] }]);
  apply([{ type: 'page.update', id: 'doc', title: '첫 변경' }], 'alpha');
  const changed = apply([{ type: 'page.update', id: 'doc', title: '두 번째 변경' }], 'alpha');
  const undone = workspace.undo({ id: 'undo-alpha', actor: 'user', expectedRevision: workspace.revision, targetCommandId: changed.commandId });
  workspace.undo({ id: 'redo-alpha', actor: 'user', expectedRevision: workspace.revision, targetCommandId: undone.commandId });
  apply([{ type: 'page.update', id: 'doc', title: '사용자 후속 변경' }]);
  workspace.recordRun({ id: 'alpha-log', runId: 'alpha', message: 'PRIVATE_RUN_PROSE', changedIds: ['doc'] });
  workspace.recordRun({ id: 'beta-log', runId: 'beta', message: '설명만 있는 기록', changedIds: ['doc'] });
  apply([{ type: 'page.create', id: 'command-only', title: '설명 없는 변경' }], 'gamma');
  const before = canonical(workspace.snapshot());
  workspace.close(); workspace = new Workspace(directory);
  const list = workspace.listRuns(), alpha = list.runs.find(run => run.runId === 'alpha');
  assert.equal(list.total, 3); assert.equal(alpha.commandCount, 4); assert.equal(alpha.logCount, 1);
  assert.equal(list.runs.find(run => run.runId === 'beta').commandCount, 0);
  assert.equal(list.runs.find(run => run.runId === 'gamma').logCount, 0);
  assert.equal(new Set([0, 1, 2].map(offset => workspace.listRuns({ limit: 1, offset }).runs[0].runId)).size, 3);
  assert.equal(workspace.listRuns({ offset: 3 }).runs.length, 0);
  const detail = workspace.runDetail('alpha', { limit: 2 });
  assert.equal(detail.commandTotal, 4); assert.equal(detail.hasMore, true);
  assert.deepEqual(detail.commands.map(command => command.id), ['redo-alpha', 'undo-alpha']);
  assert.deepEqual(workspace.runDetail('alpha', { limit: 2, offset: 2 }).commands.map(command => command.id), ['c3', 'c2']);
  assert.equal(detail.commands[0].changes[0].label, '두 번째 변경');
  assert.equal(detail.commands[0].changes[0].location, '/?id=doc');
  assert.match(detail.logs[0].createdAt, /^\d{4}-/);
  assert.equal(workspace.runDetail('beta').commands.length, 0);
  assert.equal(workspace.runDetail('gamma').logs.length, 0);
  assert.throws(() => workspace.runDetail('missing'), { code: 'NOT_FOUND' });
  assert.equal(workspace.search({ query: 'PRIVATE_RUN_PROSE' }).total, 0);
  assert.equal(canonical(workspace.snapshot()), before);
  assert.equal(workspace.get('body').entity.richText[0].text, '보존할 본문');
});

test('run log retries preserve the original record and reject a reused ID with different content', t => {
  const directory = mkdtempSync(path.join(tmpdir(), 'pageyard-run-replay-')), workspace = new Workspace(directory);
  t.after(() => { workspace.close(); rmSync(directory, { recursive: true, force: true }); });
  const input = { id: 'same-log', runId: 'run', message: '설명', changedIds: ['doc'] }, saved = workspace.recordRun(input);
  workspace.execute({ id: 'new-revision', actor: 'user', expectedRevision: 0, operations: [{ type: 'page.create', id: 'doc', title: '문서' }] });
  assert.deepEqual(workspace.recordRun(input), saved);
  assert.throws(() => workspace.recordRun({ ...input, message: '다른 설명' }), { code: 'RUN_LOG_ID_REUSED' });
  assert.throws(() => workspace.recordRun({ ...input, runId: 'different' }), { code: 'RUN_LOG_ID_REUSED' });
  assert.throws(() => workspace.recordRun({ runId: '', message: '잘못된 기록' }));
  assert.throws(() => workspace.recordRun({ runId: 'run', message: '잘못된 대상', changedIds: 'doc' }));
  assert.equal(workspace.runs('run').length, 1); assert.equal(workspace.revision, 1);
});

test('MCP run discovery and HTTP review share actual commands; log ID conflicts are explicit', async t => {
  const directory = mkdtempSync(path.join(tmpdir(), 'pageyard-run-mcp-')), workspace = new Workspace(directory), server = createLocalServer(workspace);
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const origin = `http://127.0.0.1:${server.address().port}`, client = new Client({ name: 'run-review-test', version: '1.0.0' });
  t.after(async () => { await client.close(); server.closeEventStreams(); await new Promise(resolve => server.close(resolve)); workspace.close(); rmSync(directory, { recursive: true, force: true }); });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.resolve('src/mcp.mjs')], env: { ...process.env, LOCAL_WORKSPACE_URL: origin }, stderr: 'pipe' }));
  const call = async (name, args = {}) => client.callTool({ name, arguments: args });
  assert.ok((await client.listTools()).tools.some(tool => tool.name === 'workspace_run_list'));
  const changed = (await call('workspace_apply', { id: 'work', runId: 'pilot', expectedRevision: 0, operations: [{ type: 'page.create', id: 'doc', title: '실제 항목' }] })).structuredContent;
  assert.equal((await call('workspace_run_list')).structuredContent.runs[0].commandCount, 1);
  await call('workspace_run_log', { id: 'explanation', runId: 'pilot', message: '별도 설명', changedIds: ['doc'] });
  const detail = (await call('workspace_run_read', { runId: 'pilot' })).structuredContent;
  const http = await fetch(`${origin}/api/runs/pilot`).then(response => response.json());
  assert.deepEqual(http, detail); assert.equal(http.commands[0].id, changed.commandId);
  const undone = (await call('workspace_undo', { id: 'undo-work', expectedRevision: 1, targetCommandId: changed.commandId })).structuredContent;
  assert.equal((await call('workspace_run_read', { runId: 'pilot' })).structuredContent.commands[0].id, undone.commandId);
  assert.equal((await fetch(`${origin}/api/runs`).then(response => response.json())).runs[0].commandCount, 2);
  const conflict = await call('workspace_run_log', { id: 'explanation', runId: 'pilot', message: '다른 설명' });
  assert.equal(conflict.isError, true); assert.equal(conflict.structuredContent.error.code, 'RUN_LOG_ID_REUSED');
  assert.equal((await fetch(`${origin}/api/runs?limit=0`)).status, 422);
  assert.equal((await fetch(`${origin}/api/runs/missing`)).status, 404);
});
